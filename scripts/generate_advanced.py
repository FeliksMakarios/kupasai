def clean(x):
    if isinstance(x, np.ndarray): return clean(x.tolist())
    if isinstance(x, dict): return {k:clean(v) for k,v in x.items()}
    if isinstance(x, (list,tuple)): return [clean(v) for v in x]
    if isinstance(x, (float,np.floating)): return round(float(x),8)
    if isinstance(x,np.integer): return int(x)
    return x
def write(topic,name,data,filename='data.js'):
    (ROOT/'ml-lanjut'/topic/filename).write_text('// Generated by scripts/generate_advanced.py. Seed 42 unless specified.\nvar '+name+' = '+json.dumps(clean(data),ensure_ascii=False,indent=2,allow_nan=False)+';\n')
def vec(x): return json.dumps(clean(x),ensure_ascii=False)

