def train_network(seed,keep):
    rng=np.random.default_rng(seed);W=rng.normal(0,.12,(64,40));V=rng.normal(0,.12,(40,10));b=np.zeros(40);c=np.zeros(10);mask_rng=np.random.default_rng(seed+1000)
    logs=[];best_loss=float('inf');best=None;stopped=None
    for epoch in range(1,301):
        for batch in np.array_split(rng.permutation(train),15):
            xb=X[batch];t=np.eye(10)[y[batch]];h=np.maximum(xb@W+b,0);mask=(mask_rng.random(h.shape)<keep)/keep if keep<1 else np.ones_like(h);hd=h*mask;o=hd@V+c;do=(o-t)/(len(batch)*10);dh=(do@V.T)*mask*(h>0)
            W-=.5*xb.T@dh;b-=.5*dh.sum(0);V-=.5*hd.T@do;c-=.5*do.sum(0)
        row={'epoch':epoch}
        # Test is evaluated only for the selected/final models, never per epoch.
        for key,ix in [('train',train),('val',val)]:
            out=np.maximum(X[ix]@W+b,0)@V+c;row[key+'_loss']=float(np.mean((out-np.eye(10)[y[ix]])**2));row[key+'_acc']=float(np.mean(out.argmax(1)==y[ix]))
        logs.append(row)
        if stopped is None:
            if row['val_loss']<best_loss:
                best_loss=row['val_loss'];best=(epoch,W.copy(),V.copy(),b.copy(),c.copy(),row.copy())
            elif epoch-best[0]>=15:stopped=epoch
    ep,bw,bv,bb,bc,br=best
    final_test=float(np.mean((np.maximum(X[test]@W+b,0)@V+c).argmax(1)==y[test]));best_test=float(np.mean((np.maximum(X[test]@bw+bb,0)@bv+bc).argmax(1)==y[test]))
    meta=dict(stoppedAt=stopped or 300,bestEpoch=ep,bestValLoss=best_loss,restoredValAcc=br['val_acc'],restoredTestAcc=best_test)
    return logs,meta,dict(train_acc=logs[-1]['train_acc'],val_acc=logs[-1]['val_acc'],test_acc=final_test)
